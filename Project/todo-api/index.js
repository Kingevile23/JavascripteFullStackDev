const express = require("express")
const mongoos = require("mongoose")
const cors = require("cors")
require("dotenv").config()
const todoRoutes = require("Project\todo-api\routes\todoRoutes")
const authRoutes = require("Project/todo-api/routes/AuthenRoute")
const app= require("express")
app.use(cors())
app.use(express.json())
mongoos.connect(process.env.MONGOOS_URl,{useNewUrlParser: true, useUnifiedTopology: true})
.then(() => console.log("MongoDB connecte"))
.catch(err => console.error("Erreur MongoDB: ", err))
app.use("Project\todo-api\api\todos", todoRoutes)
app.use("Project\todo-api\api\auth", authRoutes)
const PORT = process.env.PORT || 5000
app.listen(PORT, () => 
    console.log("Serveur demarre sur le port", PORT)
)
